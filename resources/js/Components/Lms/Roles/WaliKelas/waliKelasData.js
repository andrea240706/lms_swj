/**
 * Helper to calculate overall average across all subjects for a student
 */
export const calculateStudentAvg = (grades) => {
    const vals = Object.values(grades);
    if (!vals.length) return 0;
    const sum = vals.reduce((a, b) => a + b, 0);
    return Math.round((sum / vals.length) * 10) / 10;
};

/**
 * Helper to check if a student passed all minimum KKMs
 */
export const checkStudentTuntas = (grades) => {
    return daftarMapelRombel.every(m => (grades[m.code] || 0) >= m.kkm);
};
